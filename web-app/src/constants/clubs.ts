export type ClubMapKey = `${CompetitionId}-${number}`;

export function clubMapKey(competition: CompetitionId, code: number): ClubMapKey {
  return `${competition}-${code}`;
}

export const CLUBS_MAP: Record<ClubMapKey, ClubType> = CLUBS.reduce((acc, club) => {
  acc[clubMapKey(club.competition, club.code)] = club;
  return acc;
}, {} as Record<ClubMapKey, ClubType>);

export function getClubName(
  code: number,
  competitionId?: CompetitionId,
): string {
  if (competitionId) {
    const club = CLUBS_MAP[clubMapKey(competitionId, code)];
    return club ? club.name : 'Club no encontrado';
  }
  const matches = CLUBS.filter((c) => c.code === code);
  return matches[0] ? matches[0].name : 'Club no encontrado';
}

export function getClubsByCompetition(competition: CompetitionId): ClubType[] {
  return CLUBS.filter((c) => c.competition === competition);
}
